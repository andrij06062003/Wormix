#!/usr/bin/env python3
"""Writes the artifacts list (wormix-api/resources/game/artifacts.json, the server's copy) into
ConfigsConverter.as, between the ARTIFACTS-BEGIN / ARTIFACTS-END markers, so client and server
always ship the same artifacts. Run from the repo root, then rebuild Wormix.swf (see README.md).

Every artifact gets "artifact": true and "charName": "default" (they are stored with the hats of
every race). An artifact whose bonuses have no effect in 1.05.0 yet is hidden ("hideInShop" in
artifacts.json, so the server refuses to sell it too)."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "wormix-api/resources/game/artifacts.json"
DST = pathlib.Path(__file__).resolve().parent / "ConfigsConverter.as"


def as3(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    return str(value)


def main():
    entries = []
    for art in json.loads(SRC.read_text(encoding="utf-8")):
        art = dict(art)
        art["artifact"] = True
        art["charName"] = "default"
        art["infinite"] = True
        body = ",".join(f'"{k}":{as3(v)}' for k, v in art.items())
        entries.append("{" + body + "}")
    block = ("      // ARTIFACTS-BEGIN (generated by gen_artifacts_config.py from artifacts.json)\n"
             "      private static const ARTIFACTS:Array = [\n         "
             + ",\n         ".join(entries) +
             "];\n      // ARTIFACTS-END\n")
    text = DST.read_text(encoding="utf-8")
    text, n = re.subn(r"      // ARTIFACTS-BEGIN.*?// ARTIFACTS-END\n", lambda _: block, text, flags=re.S)
    if n != 1:
        raise SystemExit("markers not found in " + str(DST))
    DST.write_text(text, encoding="utf-8")
    print(f"{len(entries)} artifacts written to {DST.name}")


if __name__ == "__main__":
    main()
